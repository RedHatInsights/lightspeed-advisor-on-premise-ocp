#!/usr/bin/env python3
"""Fail CI when a leak-investigation summary exceeds an RSS growth limit.

Reads the summary.txt generated by scripts/run-leak-investigation.sh and compares
its rss_delta_mib value with MEMORY_MAX_RSS_DELTA_MIB.

Examples:
    MEMORY_MAX_RSS_DELTA_MIB=125 \
        scripts/check-leak-summary.py /path/to/summary.txt
    MEMORY_SUMMARY_PATH=/path/to/summary.txt MEMORY_MAX_RSS_DELTA_MIB=150 \
        scripts/check-leak-summary.py
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

THRESHOLD_ENV = "MEMORY_MAX_RSS_DELTA_MIB"
SUMMARY_PATH_ENV = "MEMORY_SUMMARY_PATH"


def parse_summary(path: Path) -> dict[str, str]:
    """Parse key=value lines from a leak-investigation summary file."""
    values: dict[str, str] = {}
    try:
        lines = path.read_text().splitlines()
    except OSError as exc:
        raise ValueError(f"could not read summary file {path}: {exc}") from exc

    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()

    return values


def require_float(values: dict[str, str], key: str) -> float:
    """Read a required numeric summary value."""
    if key not in values:
        raise ValueError(f"summary is missing required key: {key}")
    try:
        return float(values[key])
    except ValueError as exc:
        raise ValueError(f"summary key {key} is not numeric: {values[key]!r}") from exc


def require_int(values: dict[str, str], key: str) -> int:
    """Read a required integer summary value."""
    if key not in values:
        raise ValueError(f"summary is missing required key: {key}")
    try:
        return int(values[key])
    except ValueError as exc:
        raise ValueError(
            f"summary key {key} is not an integer: {values[key]!r}"
        ) from exc


def read_threshold() -> float:
    """Read the RSS delta threshold from the environment."""
    raw_limit = os.environ.get(THRESHOLD_ENV)
    if raw_limit is None:
        raise ValueError(f"set {THRESHOLD_ENV} to the maximum allowed RSS delta in MiB")
    try:
        limit = float(raw_limit)
    except ValueError as exc:
        raise ValueError(
            f"{THRESHOLD_ENV} must be numeric, got: {raw_limit!r}"
        ) from exc
    if limit < 0:
        raise ValueError(f"{THRESHOLD_ENV} must be non-negative, got: {limit}")
    return limit


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Check scripts/run-leak-investigation.sh summary.txt against "
            f"${THRESHOLD_ENV}."
        )
    )
    parser.add_argument(
        "summary_path",
        nargs="?",
        default=os.environ.get(SUMMARY_PATH_ENV, "summary.txt"),
        help=(
            "Path to summary.txt. Defaults to $MEMORY_SUMMARY_PATH if set, "
            "otherwise ./summary.txt."
        ),
    )
    return parser


def main() -> int:
    args = build_arg_parser().parse_args()
    summary_path = Path(args.summary_path)

    try:
        limit_mib = read_threshold()
        summary = parse_summary(summary_path)
        rss_delta_mib = require_float(summary, "rss_delta_mib")
        success_requests = require_int(summary, "success_requests")
        failed_requests = require_int(summary, "failed_requests")
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    print(f"summary_path={summary_path}")
    print(f"success_requests={success_requests}")
    print(f"failed_requests={failed_requests}")
    print(f"rss_delta_mib={rss_delta_mib:.2f}")
    print(f"memory_max_rss_delta_mib={limit_mib:.2f}")

    if success_requests <= 0:
        print(f"FAIL: leak test had no successful upload requests ({success_requests})")
        return 1

    if failed_requests != 0:
        print(f"FAIL: leak test had {failed_requests} failed upload request(s)")
        return 1

    if rss_delta_mib > limit_mib:
        excess_mib = rss_delta_mib - limit_mib
        print(
            "FAIL: possible memory leak detected: "
            f"RSS grew by {rss_delta_mib:.2f} MiB, "
            f"exceeding the {limit_mib:.2f} MiB limit by {excess_mib:.2f} MiB"
        )
        return 1

    headroom_mib = limit_mib - rss_delta_mib
    print(
        "PASS: RSS growth is within limit: "
        f"{rss_delta_mib:.2f} MiB <= {limit_mib:.2f} MiB "
        f"({headroom_mib:.2f} MiB headroom)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
