#!/usr/bin/env python3
"""Fail CI when a leak-investigation summary exceeds an RSS growth limit.

Reads the summary.txt generated by scripts/run-leak-investigation.sh and compares
its rss_delta_mib value with MEMORY_MAX_RSS_DELTA_MIB.

Examples:
    MEMORY_MAX_RSS_DELTA_MIB=125 \
        scripts/check-leak-summary.py /path/to/summary.txt
    MEMORY_SUMMARY_PATH=/path/to/summary.txt MEMORY_MAX_RSS_DELTA_MIB=150 \
        scripts/check-leak-summary.py
"""

from __future__ import annotations

import os
from pathlib import Path

import click

THRESHOLD_ENV = "MEMORY_MAX_RSS_DELTA_MIB"
SUMMARY_PATH_ENV = "MEMORY_SUMMARY_PATH"


def parse_summary(path: Path) -> dict[str, str]:
    """Parse key=value lines from a leak-investigation summary file."""
    values: dict[str, str] = {}
    try:
        lines = path.read_text().splitlines()
    except OSError as exc:
        raise ValueError(f"could not read summary file {path}: {exc}") from exc

    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()

    ensure_float(values, "rss_delta_mib")
    ensure_int(values, "success_requests")
    ensure_int(values, "failed_requests")

    return values


def ensure_float(values: dict[str, str], key: str) -> None:
    """Ensure that a required summary value is a float."""
    if key not in values:
        raise ValueError(f"summary is missing required key: {key}")
    try:
        values[key] = float(values[key])
    except ValueError as exc:
        raise ValueError(f"summary key {key} is not numeric: {values[key]!r}") from exc


def ensure_int(values: dict[str, str], key: str) -> None:
    """Ensure that a required summary value is an integer."""
    if key not in values:
        raise ValueError(f"summary is missing required key: {key}")
    try:
        values[key] = int(values[key])
    except ValueError as exc:
        raise ValueError(
            f"summary key {key} is not an integer: {values[key]!r}"
        ) from exc


def read_threshold() -> float:
    """Read the RSS delta threshold from the environment."""
    raw_limit = os.environ.get(THRESHOLD_ENV, "")
    try:
        limit = float(raw_limit)
    except ValueError as exc:
        raise ValueError(
            f"{THRESHOLD_ENV} must be defined and be numeric, got: {raw_limit!r}"
        ) from exc
    if limit < 0:
        raise ValueError(f"{THRESHOLD_ENV} must be non-negative, got: {limit}")
    return limit


@click.command(
    help=(
        f"Check scripts/run-leak-investigation.sh summary.txt against ${THRESHOLD_ENV}."
    )
)
@click.argument(
    "summary_path",
    required=False,
    type=click.Path(dir_okay=False, path_type=Path),
    default=lambda: Path(os.environ.get(SUMMARY_PATH_ENV, "summary.txt")),
)
def main(summary_path: Path) -> None:
    """CLI entrypoint."""
    try:
        limit_mib = read_threshold()
        summary = parse_summary(summary_path)
        rss_delta_mib = summary["rss_delta_mib"]
        success_requests = summary["success_requests"]
        failed_requests = summary["failed_requests"]

    except ValueError as exc:
        click.echo(f"ERROR: {exc}", err=True)
        raise click.exceptions.Exit(2) from exc

    click.echo(f"summary_path={summary_path}")
    click.echo(f"success_requests={success_requests}")
    click.echo(f"failed_requests={failed_requests}")
    click.echo(f"rss_delta_mib={rss_delta_mib:.2f}")
    click.echo(f"memory_max_rss_delta_mib={limit_mib:.2f}")

    if success_requests <= 0:
        click.echo(
            f"FAIL: leak test had no successful upload requests ({success_requests})"
        )
        SystemExit(1)

    if failed_requests != 0:
        click.echo(f"FAIL: leak test had {failed_requests} failed upload request(s)")
        SystemExit(1)

    if rss_delta_mib > limit_mib:
        excess_mib = rss_delta_mib - limit_mib
        click.echo(
            "FAIL: possible memory leak detected: "
            f"RSS grew by {rss_delta_mib:.2f} MiB, "
            f"exceeding the {limit_mib:.2f} MiB limit by {excess_mib:.2f} MiB"
        )
        SystemExit(1)

    headroom_mib = limit_mib - rss_delta_mib
    click.echo(
        "PASS: RSS growth is within limit: "
        f"{rss_delta_mib:.2f} MiB <= {limit_mib:.2f} MiB "
        f"({headroom_mib:.2f} MiB headroom)"
    )


if __name__ == "__main__":
    main()
