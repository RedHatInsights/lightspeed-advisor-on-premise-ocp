#!/usr/bin/env python3
"""Generate the pull-request comment body for the memory leak workflow.

The workflow uploads the full report directory as an artifact. GitHub artifact
files do not have stable raw-file URLs that can be embedded directly as images,
so this script also builds a small QuickChart image URL from memory.log for the
inline preview. The matplotlib PNGs generated by scripts/plot_memory.py remain
available in the uploaded artifact.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from urllib.parse import quote

MARKER = "<!-- memory-leak-pr-report -->"


def read_text_or_default(path: Path, default: str = "not available") -> str:
    try:
        return path.read_text().strip()
    except OSError:
        return default


def load_memory_samples(memory_log: Path) -> list[tuple[float, float]]:
    """Read memory.log as (epoch_seconds, MiB) samples."""
    samples: list[tuple[float, float]] = []
    if not memory_log.exists():
        return samples

    for line in memory_log.read_text().splitlines():
        parts = line.split()
        if len(parts) != 2:
            continue
        try:
            timestamp = float(parts[0])
            mib = float(parts[1]) / 1024.0
        except ValueError:
            continue
        samples.append((timestamp, mib))
    return samples


def build_quickchart_url(samples: list[tuple[float, float]], fallback_url: str) -> str:
    """Build an embeddable memory graph URL from memory.log samples."""
    if not samples:
        return fallback_url

    max_points = 60
    step = max(1, (len(samples) + max_points - 1) // max_points)
    decimated = samples[::step]
    if decimated[-1] != samples[-1]:
        decimated.append(samples[-1])

    start_timestamp = samples[0][0]
    chart_config = {
        "type": "line",
        "data": {
            "labels": [
                str(round(timestamp - start_timestamp)) for timestamp, _ in decimated
            ],
            "datasets": [
                {
                    "label": "Process RSS (MiB)",
                    "data": [round(mib, 2) for _, mib in decimated],
                    "borderColor": "#1f77b4",
                    "backgroundColor": "rgba(31, 119, 180, 0.12)",
                    "fill": False,
                    "pointRadius": 0,
                }
            ],
        },
        "options": {
            "title": {"display": True, "text": "Memory usage over time"},
            "legend": {"display": True},
            "scales": {
                "xAxes": [
                    {
                        "scaleLabel": {
                            "display": True,
                            "labelString": "Seconds since start",
                        }
                    }
                ],
                "yAxes": [
                    {"scaleLabel": {"display": True, "labelString": "Memory (MiB)"}}
                ],
            },
        },
    }

    encoded_config = quote(json.dumps(chart_config, separators=(",", ":")))
    return f"https://quickchart.io/chart?width=900&height=450&format=png&c={encoded_config}"


def detect_graph_name(report_dir: Path) -> str:
    if (report_dir / "memory_vs_processed_archives.png").exists():
        return "memory_vs_processed_archives.png"
    return "memory_vs_time.png"


def build_comment(report_dir: Path, artifact_url: str) -> str:
    summary = read_text_or_default(report_dir / "summary.txt")
    check_log = read_text_or_default(report_dir / "check-leak-summary.log")
    graph_name = detect_graph_name(report_dir)
    chart_url = build_quickchart_url(
        load_memory_samples(report_dir / "memory.log"), artifact_url
    )

    return f"""{MARKER}
## Memory leak check report

![Memory usage graph]({chart_url})

Generated matplotlib graph image `{graph_name}` is included in the uploaded artifact:
[memory-leak-pr-report]({artifact_url}).

<details>
<summary>summary.txt</summary>

```text
{summary}
```
</details>

<details>
<summary>check-leak-summary.log</summary>

```text
{check_log}
```
</details>
"""


def default_artifact_url() -> str:
    server_url = os.environ.get("GITHUB_SERVER_URL", "https://github.com")
    repository = os.environ.get("GITHUB_REPOSITORY", "")
    run_id = os.environ.get("GITHUB_RUN_ID", "")
    if repository and run_id:
        return f"{server_url}/{repository}/actions/runs/{run_id}"
    return server_url


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate memory leak PR comment markdown"
    )
    parser.add_argument(
        "report_dir",
        type=Path,
        help="Report directory generated by run-leak-investigation.sh",
    )
    parser.add_argument(
        "--artifact-url",
        default=os.environ.get("ARTIFACT_URL") or default_artifact_url(),
        help="URL of the uploaded memory-leak-pr-report artifact",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Write markdown to this path instead of stdout",
    )
    return parser


def main() -> int:
    args = build_arg_parser().parse_args()
    artifact_url = args.artifact_url or default_artifact_url()
    comment = build_comment(args.report_dir, artifact_url)

    if args.output:
        args.output.write_text(comment)
    else:
        print(comment, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
